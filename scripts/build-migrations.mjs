// Turns the drizzle-kit output (src/db/migrations/*.sql + meta/_journal.json)
// into a single self-contained TypeScript module the app can import directly:
// src/db/migrations/bundle.ts
//
// Why not import the .sql files on device: Metro would need either a custom
// transformer or `babel-plugin-inline-import` (unmaintained since 2022). Inlining
// the SQL into a .ts file at generate time keeps the runtime dependency-free.
//
// Run via `npm run db:generate` (drizzle-kit generate && node scripts/build-migrations.mjs).

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const migrationsDir = join(dirname(fileURLToPath(import.meta.url)), '../src/db/migrations');
const journal = JSON.parse(readFileSync(join(migrationsDir, 'meta/_journal.json'), 'utf8'));

const entries = journal.entries
  .slice()
  .sort((a, b) => a.idx - b.idx)
  .map((entry) => ({
    tag: entry.tag,
    key: `m${String(entry.idx).padStart(4, '0')}`,
    sql: readFileSync(join(migrationsDir, `${entry.tag}.sql`), 'utf8'),
  }));

const backtick = (sql) => '`' + sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';

const file = `// GENERATED by scripts/build-migrations.mjs — do not edit by hand.
// Regenerate with \`npm run db:generate\` after any schema change.

const journal = ${JSON.stringify(journal, null, 2)};

const migrations: Record<string, string> = {
${entries.map((e) => `  ${e.key}: ${backtick(e.sql)},`).join('\n')}
};

/** Consumed by \`useMigrations\` / \`migrate\` from \`drizzle-orm/expo-sqlite/migrator\`. */
export default { journal, migrations };
`;

writeFileSync(join(migrationsDir, 'bundle.ts'), file);
console.log(`bundle.ts written with ${entries.length} migration(s): ${entries.map((e) => e.tag).join(', ')}`);
